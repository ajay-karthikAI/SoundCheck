    iso_week INTEGER NOT NULL,
    scope_type VARCHAR NOT NULL,
    scope_id VARCHAR NOT NULL,
    estimate_status VARCHAR NOT NULL,
    listening_entropy DOUBLE,
    listening_entropy_ci_low DOUBLE,
    listening_entropy_ci_high DOUBLE,
    effective_genres DOUBLE,
    effective_genres_ci_low DOUBLE,
    effective_genres_ci_high DOUBLE,
    conversation_hhi DOUBLE,
    conversation_hhi_ci_low DOUBLE,
    conversation_hhi_ci_high DOUBLE,
    listening_top_share DOUBLE,
    listening_top_share_ci_low DOUBLE,
