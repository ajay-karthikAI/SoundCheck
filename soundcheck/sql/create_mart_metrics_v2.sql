    taxonomy_version VARCHAR NOT NULL,
    week_start DATE NOT NULL,
    iso_year INTEGER NOT NULL,
    iso_week INTEGER NOT NULL,
    genre_id VARCHAR NOT NULL,
    display_name VARCHAR NOT NULL,
    macro_family_id VARCHAR NOT NULL,
    parent_genre_id VARCHAR,
    coverage_state VARCHAR NOT NULL,
    estimate_status VARCHAR NOT NULL,
    estimate_eligible BOOLEAN NOT NULL,
    conversation_score_raw DOUBLE,
    listening_playcount_delta DOUBLE,
    listening_listeners_delta DOUBLE,
    listening_score_raw DOUBLE,
    supply_release_groups_raw DOUBLE,
    conversation_score_shrunk DOUBLE,
    conversation_effective_n DOUBLE,
    conversation_subgenre_shrinkage_weight DOUBLE,
    conversation_family_shrinkage_weight DOUBLE,
    conversation_combined_shrinkage_weight DOUBLE,
